export type MessageKey = keyof (typeof messages)['en'];

export function isMessageKey(value: string): value is MessageKey {
  return Object.hasOwn(messages.en, value);
}

export function resolveLocale(mode: LocaleMode, systemLocale: string): 'en' | 'ja' {
  if (mode === 'en' || mode === 'ja') return mode;
  return systemLocale.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

export function formatMessage(
  locale: 'en' | 'ja',
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  return Object.entries(values).reduce<string>(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    String(messages[locale][key]),
  );
}
