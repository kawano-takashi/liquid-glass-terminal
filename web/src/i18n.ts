export function resolveLocale(locale: Locale, browserLocale = navigator.language): ResolvedLocale {
  if (locale === 'en' || locale === 'ja') return locale;
  return browserLocale.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}
